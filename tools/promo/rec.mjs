import {session,srv} from './cap.mjs';
import fs from 'fs';
const VD=new URL('./vid',import.meta.url).pathname;fs.rmSync(VD,{recursive:true,force:true});fs.mkdirSync(VD,{recursive:true});
const t0=Date.now();
const {b,pg,ctx}=await session({zoom:true,video:VD});
const marks={};const mark=n=>{marks[n]=(Date.now()-t0)/1000;};
await pg.addStyleTag({content:`.tapdot{position:fixed;width:64px;height:64px;margin:-32px 0 0 -32px;border-radius:50%;background:rgba(59,91,219,.35);border:3px solid rgba(59,91,219,.8);z-index:9999;pointer-events:none;animation:tap .55s ease-out forwards}@keyframes tap{from{transform:scale(.4);opacity:1}to{transform:scale(1.25);opacity:0}}`});
await pg.evaluate(()=>{window.addEventListener('pointerdown',e=>{const d=document.createElement('div');d.className='tapdot';d.style.left=e.clientX+'px';d.style.top=e.clientY+'px';document.body.appendChild(d);setTimeout(()=>d.remove(),600);},true);});
const tap=async(sel)=>{const el=await pg.$(sel);await el.scrollIntoViewIfNeeded();const bb=await el.boundingBox();await pg.mouse.move(bb.x+bb.width/2,bb.y+bb.height/2,{steps:8});await pg.waitForTimeout(150);await pg.mouse.down();await pg.waitForTimeout(90);await pg.mouse.up();};
const smooth=async(y)=>{await pg.evaluate(y=>document.querySelector('.sheet').scrollTo({top:y,behavior:'smooth'}),y);await pg.waitForTimeout(900);};
await pg.waitForTimeout(1800);mark('home');
await tap('[data-act=add]');await pg.waitForTimeout(700);mark('add');
await tap('#f-amount');await pg.keyboard.type('3480',{delay:230});await pg.waitForTimeout(900);
await tap('[data-act=payer][data-w=b]');await pg.waitForTimeout(1100);mark('who');
await smooth(9999);await pg.waitForTimeout(700);mark('ratio');
const r=await pg.$('#f-ratio');const bb=await r.boundingBox();
const xAt=p=>bb.x+bb.width*p;
await pg.mouse.move(xAt(0.7),bb.y+bb.height/2,{steps:6});await pg.mouse.down();await pg.mouse.move(xAt(0.5),bb.y+bb.height/2,{steps:22});await pg.mouse.up();await pg.waitForTimeout(1100);
await smooth(0);await pg.waitForTimeout(400);mark('save');
await tap('[data-act=save]');await pg.waitForTimeout(1600);mark('saved');
await tap('[data-act=settle]');await pg.waitForTimeout(1900);mark('settle');
await tap('[data-act=settle-ok]');await pg.waitForSelector('.done-ov');mark('done');await pg.waitForTimeout(2300);
await tap('[data-act=tab][data-v=report]');await pg.waitForTimeout(1200);mark('report');
await pg.evaluate(()=>window.scrollTo({top:620,behavior:'smooth'}));await pg.waitForTimeout(3000);mark('end');
marks.total=(Date.now()-t0)/1000;
await ctx.close();await b.close();srv.close();
const f=fs.readdirSync(VD).find(x=>x.endsWith('.webm'));
fs.writeFileSync(VD+'/marks.json',JSON.stringify({marks,file:f}));console.log(marks,f);
